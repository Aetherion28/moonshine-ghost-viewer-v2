#!/usr/bin/env python3
"""Generates npcdata.ts from the decomp: each NPC kind's hit sizes and Peach's carry offset
(NPC/NpcInitData.cpp sAllNpcInitData), and the animation kind -> BCK / BTP index tables with the
per-kind BTP remaps (NPC/NpcInitAnmData.cpp sAllNpcInitAnmData). Both files match the DOL.

    python3 gen_npcdata.py /path/to/sms-ai-decomp > npcdata.ts
"""
import json, re, sys

root = sys.argv[1] if len(sys.argv) > 1 else '/home/claude/sms-ai-decomp'
init = open(root + '/src/NPC/NpcInitData.cpp', encoding='utf-8').read()
anm = open(root + '/src/NPC/NpcInitAnmData.cpp', encoding='utf-8').read()

# ---- hit sizes: TNpcInitInfo's four floats, and its take data
infos = {}
for m in re.finditer(r'static const TNpcInitInfo (\w+) = \{(.*?)\n\};', init, re.S):
    body = m.group(2)
    nums = re.findall(r'(-?\d+\.\d+)f', body)
    take = re.match(r'\s*(&\w+|nullptr)', body).group(1)
    infos[m.group(1)] = {'hit': [float(x) for x in nums[-4:]], 'take': take}
takes = {}
for m in re.finditer(r'static const TNpcTakeData (\w+)\s*=\s*\{\s*"([^"]+)",\s*"([^"]+)"\s*\};', init):
    takes['&' + m.group(1)] = [m.group(2), m.group(3)]
order = re.search(r'sAllNpcInitData\[\] = \{(.*?)\};', init, re.S).group(1)
kinds = []
for tok in re.findall(r'&\w+|nullptr', order):
    if tok == 'nullptr': kinds.append(None); continue
    i = infos[tok[1:]]
    kinds.append({'hit': i['hit'], 'take': takes.get(i['take'])})

# ---- animation tables
tables = {}
for m in re.finditer(r'static const TLodAnmIndex (\w+)\[\] = \{(.*?)\n\};', anm, re.S):
    rows = re.findall(r'\{\s*\{\s*(-?\d+),\s*(-?\d+)\s*\},\s*\{\s*(-?\d+),\s*(-?\d+)\s*\}\s*\}', m.group(2))
    tables[m.group(1)] = [[int(a), int(b), int(c), int(d)] for a, b, c, d in rows]
remaps = {}
for m in re.finditer(r'static const TAnmBtpMapping (\w+)\[\] = \{(.*?)\};', anm, re.S):
    remaps[m.group(1)] = [[int(a), int(b)] for a, b in re.findall(r'\{\s*(-?\d+),\s*(-?\d+)\s*\}', m.group(2))]
alls = re.search(r'sAllNpcInitAnmData\[\] = \{(.*?)\};', anm, re.S).group(1)
anms = []
for a, b in re.findall(r'\{\s*(\w+),\s*(\w+)\s*\}', alls):
    anms.append({'index': tables.get(a), 'btp': remaps.get(b)})

print('// NPC data from the decomp (NPC/NpcInitData.cpp, NPC/NpcInitAnmData.cpp, both matching main.dol).')
print('// Generated by gen_npcdata.py; don\'t edit by hand.')
print('/* eslint-disable */')
print('/** by ACTOR_TYPE_NPC_* - ACTOR_TYPE_NPC_MONTE_M: hit [attack radius, attack height, damage radius, damage height], take [model, joint] */')
print('export const NPC_INIT: ({ hit: number[]; take: string[] | null } | null)[] = ' + json.dumps(kinds) + ';')
print('/** TLodAnmIndex rows [bck lod0, bck lod1, btp lod0, btp lod1] by EnumNpcAnmKind (the -2 row ends it), and the kind\'s BTP remap */')
print('export const NPC_ANM: { index: number[][] | null; btp: number[][] | null }[] = ' + json.dumps(anms) + ';')
