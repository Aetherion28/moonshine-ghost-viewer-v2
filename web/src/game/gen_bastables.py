#!/usr/bin/env python3
"""Generates bastables.ts: every live actor's animation-sound table (getBasNameTable, the
*_bastable arrays in the decomp's Enemy/, NPC/, Animal/ sources), keyed by class name without its
leading T (as the sim's classes are named).

    python3 gen_bastables.py /path/to/sms-ai-decomp > bastables.ts
"""
import json, re, sys, glob

root = sys.argv[1] if len(sys.argv) > 1 else '/home/claude/sms-ai-decomp'
tables, owners = {}, {}
for path in sorted(glob.glob(root + '/src/**/*.cpp', recursive=True)):
    src = open(path, encoding='utf-8', errors='replace').read()
    src = re.sub(r'//[^\n]*', '', src)
    src = re.sub(r'/\*.*?\*/', '', src, flags=re.S)
    for m in re.finditer(r'(?:static\s+)?(?:const\s+)?char\s*\*\s*(?:const\s+)?(\w+)\s*\[\s*\w*\s*\]\s*=\s*\{(.*?)\};', src, re.S):
        name, body = m.group(1), m.group(2)
        items = [x.strip() for x in body.split(',') if x.strip()]
        vals = []
        for it in items:
            if it in ('nullptr', 'NULL', '0'):
                vals.append(None)
            elif it.startswith('"'):
                vals.append(json.loads(it))
            else:
                vals = None
                break
        if vals is not None and any(v and v.lower().endswith('.bas') for v in vals):
            tables[name] = vals
    for m in re.finditer(r'const\s+char\s*\*\*\s*T?(\w+)::getBasNameTable\(\)\s*const\s*\{(.*?)\n?\}', src, re.S):
        cls, body = m.group(1), m.group(2)
        r = re.search(r'return\s+(\w+)\s*;', body)
        if r and r.group(1) != 'nullptr':
            owners[cls] = r.group(1)
out = {}
for cls, t in owners.items():
    if t in tables:
        out[cls] = tables[t]
    else:
        print(f'// (no table {t} for {cls})')
print('// Every live actor\'s animation-sound table (TLiveActor::getBasNameTable), by class name without its T.')
print('// Generated by gen_bastables.py from the decomp; don\'t edit by hand.')
print('/* eslint-disable */')
npc = {k: v for k, v in tables.items() if re.match(r'(monte|mare|kino|peach|raccoon|sunflower)', k)}
print('/** the NPCs\' tables by their names (TBaseNPC::getBasNameTable picks one by actor type) */')
print('export const NPC_BAS_TABLES: Record<string, (string | null)[]> = ' + json.dumps(npc, ensure_ascii=False, separators=(',', ':')) + ';')
print('export const BAS_TABLES: Record<string, (string | null)[]> = ' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';')
