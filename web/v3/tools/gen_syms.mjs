// Writes game/syms_jp10.ts: the addresses of the few functions v3 hooks by name, so the browser needs no
// symbol file. A name is taken when it stands quoted in the code that asks for symbols (ppc/hle.ts,
// ppc/machine.ts, game/*.ts) and the decomp's symbols.txt has a function of that name.
// node v3/tools/gen_syms.mjs [symbols.txt]   (from web/)
import fs from 'node:fs';
import path from 'node:path';

const here = path.dirname(new URL(import.meta.url).pathname), v3 = path.join(here, '..');
const symbols = process.argv[2] || '/home/claude/sms-ai-decomp/config/GMSJ01/symbols.txt';
const out = path.join(v3, 'game/syms_jp10.ts');
const funcs = new Map();
for (const l of fs.readFileSync(symbols, 'utf8').split('\n')) {
    const m = /^(\S+) = \.\w+:0x([0-9A-F]+); \/\/ type:function size:0x([0-9A-F]+)/.exec(l);
    if (m) funcs.set(m[1], parseInt(m[2], 16));
}
const sources = ['ppc/hle.ts', 'ppc/machine.ts', ...fs.readdirSync(path.join(v3, 'game')).filter((f) => f.endsWith('.ts') && f !== 'syms_jp10.ts').map((f) => 'game/' + f)];
const names = new Set();
for (const s of sources) for (const m of fs.readFileSync(path.join(v3, s), 'utf8').matchAll(/'([A-Za-z_][A-Za-z0-9_]*)'/g)) if (funcs.has(m[1])) names.add(m[1]);
const list = [...names].sort();
const text = `// Generated by tools/gen_syms.mjs from the decomp's symbols.txt (GMSJ01 revision 0): the functions v3 hooks by name.
import type { Sym } from '../ppc/hle.js';

export const SYMS_JP10: Record<string, number> = {
${list.map((n) => `    ${n}: 0x${funcs.get(n).toString(16).toUpperCase()},`).join('\n')}
};
export const symJP10: Sym = (name) => SYMS_JP10[name];
`;
fs.writeFileSync(out, text);
console.log(`${list.length} names -> ${out}`);
